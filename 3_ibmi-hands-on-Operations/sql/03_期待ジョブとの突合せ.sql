-- 2. 突合せ：停止／応答待ち／稼働中
SELECT E.JOB_NAME    AS ジョブ名,
       E.DESCRIPTION AS 業務説明,
       E.PRIORITY    AS 重要度,
       CASE WHEN A.JOB_NAME_SHORT IS NULL THEN '停止'
            WHEN A.JOB_STATUS = 'MSGW'    THEN '応答待ち'
            ELSE '稼働中' END            AS 判定,
       A.JOB_STATUS  AS 現在の状況,
       E.CONTACT     AS エスカレーション先
  FROM STUDY01.EXPECTED_JOBS E
  LEFT JOIN TABLE(QSYS2.ACTIVE_JOB_INFO(
         SUBSYSTEM_LIST_FILTER => 'HANDSON',
         DETAILED_INFO         => 'NONE')) A
         ON A.JOB_NAME_SHORT = E.JOB_NAME
        AND A.SUBSYSTEM      = E.SUBSYSTEM
 ORDER BY CASE WHEN A.JOB_NAME_SHORT IS NULL THEN 0
               WHEN A.JOB_STATUS = 'MSGW'    THEN 1 ELSE 2 END,
          E.PRIORITY, E.JOB_NAME;

-- 3. 原因調査：ヒストリーログ（直近2時間）
--    OPS01B は CPF1241（正常終了）になる点に注意。終了コードだけでは停止に気づけない
SELECT MESSAGE_TIMESTAMP, MESSAGE_ID, FROM_JOB, MESSAGE_TEXT
  FROM TABLE(QSYS2.HISTORY_LOG_INFO(
         START_TIME => CURRENT TIMESTAMP - 2 HOURS)) X
 WHERE FROM_JOB LIKE '%/OPS01B'
    OR MESSAGE_TEXT LIKE '%OPS01B%'
 ORDER BY MESSAGE_TIMESTAMP;

-- 4. 原因調査：運用メッセージ待ち行列
SELECT MESSAGE_TIMESTAMP, MESSAGE_TYPE, FROM_JOB, MESSAGE_TEXT
  FROM QSYS2.MESSAGE_QUEUE_INFO
 WHERE MESSAGE_QUEUE_LIBRARY = 'STUDY01'
   AND MESSAGE_QUEUE_NAME    = 'OPSMSGQ'
 ORDER BY MESSAGE_TIMESTAMP;

