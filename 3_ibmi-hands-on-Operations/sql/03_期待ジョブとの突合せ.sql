-- 1. 期待ジョブ定義テーブル
CREATE TABLE STUDY01.EXPECTED_JOBS (
  JOB_NAME      CHAR(10)     NOT NULL PRIMARY KEY,
  SUBSYSTEM     CHAR(10)     NOT NULL,
  DESCRIPTION   VARCHAR(100),
  START_COMMAND VARCHAR(512),
  PRIORITY      CHAR(1)      NOT NULL DEFAULT 'B',
  CONTACT       VARCHAR(50)
);

